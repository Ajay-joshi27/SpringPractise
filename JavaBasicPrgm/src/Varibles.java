
public class Varibles {

	public static void main(String[] args) {
		String name="Anusha";
		int age =2;
		System.out.println(name);
		System.out.println(age);
		
		int a=45;
		int b=31;
		System.out.println(a+b);
		System.out.println(a-b);
		System.out.println(a*b);
		System.out.println(a==b);
		
	

		for(int i=1;i<=3;i++) {
			for(int j=1;j<=3;j++) {
				System.out.print('*');
			}
			System.out.println();
		}
	}

}
